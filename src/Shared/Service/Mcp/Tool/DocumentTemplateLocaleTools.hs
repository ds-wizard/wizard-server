documentTemplateLocaleTools :: WizardRequestContextC s m => [McpTool m]
documentTemplateLocaleTools = [getDocumentTemplateTranslation, saveDocumentTemplateLocale, deleteDocumentTemplateLocale]

getDocumentTemplateTranslation :: WizardRequestContextC s m => McpTool m
getDocumentTemplateTranslation =
  markThirdPartyFields [["content"]] $
    McpTool
      { name = "get_document_template_translation"
      , title = "Get document template translation"
      , description =
          "Get the translation template (POT, generated by the document worker after a release) of a document template, or with locale_uuid the PO file of one of its locales (listed in get_document_template). "
            ++ "Translate the template and save it with save_document_template_locale; long content is cut, call it again with the cursor of the result to read on"
      , inputSchema = argumentsSchema arguments
      , outputSchema = Just $ objectSchema ["content"] [("content", stringSchema)]
      , annotations = readOnlyAnnotations
      , continuable = True
      , permissions = [_MCP_READ_ROLE_PERMISSION]
      , toolset = Just DtMcpToolset
      , transactionState = NoTransaction
      , run = withArguments arguments $ \(dtUuid, mLocaleUuid) -> (\content -> object ["content" .= decodeText content]) <$> getTranslation dtUuid mLocaleUuid
      }
  where
    arguments = (,) <$> templateUuidArgument <*> optionalArgument "locale_uuid" "The locale whose PO file to get; leave it out for the translation template"

getTranslation :: WizardRequestContextC s m => U.UUID -> Maybe U.UUID -> m BS.ByteString
getTranslation dtUuid Nothing = snd <$> getPotFile dtUuid
getTranslation dtUuid (Just localeUuid) = getLocaleContent dtUuid localeUuid

saveDocumentTemplateLocale :: WizardRequestContextC s m => McpTool m
saveDocumentTemplateLocale =
  McpTool
    { name = "save_document_template_locale"
    , title = "Save document template locale"
    , description =
        "Add a translation (a PO file translated from get_document_template_translation) to a document template; its Language header gives the locale code "
          ++ "and a locale of the same code is replaced. name defaults to the X-Display-Name header or the code"
    , inputSchema = argumentsSchema arguments
    , outputSchema = Just $ jsonSchema (Proxy :: Proxy DocumentTemplateLocaleList)
    , annotations = idempotentWriteAnnotations
    , continuable = False
    , permissions = [_MCP_READ_ROLE_PERMISSION, _MCP_WRITE_ROLE_PERMISSION, _DOCUMENT_TEMPLATES_MANAGE_ROLE_PERMISSION]
    , toolset = Just DtMcpToolset
    , transactionState = Transactional
    , run = withArguments arguments $ \(dtUuid, mName, content) -> toJSON <$> saveLocaleFromPo dtUuid mName content
    }
  where
    arguments =
      (,,)
        <$> templateUuidArgument
        <*> optionalArgument "name" "The name of the locale"
        <*> requiredTextContentArgument mcpMaxBase64ContentSize "content" "The PO file, at most 10 MB"

deleteDocumentTemplateLocale :: WizardRequestContextC s m => McpTool m
deleteDocumentTemplateLocale =
  McpTool
    { name = "delete_document_template_locale"
    , title = "Delete document template locale"
    , description = "Delete a locale of a document template; documents can no longer be generated in its language"
    , inputSchema = argumentsSchema arguments
    , outputSchema = Just $ objectSchema [] []
    , annotations = destructiveAnnotations
    , continuable = False
    , permissions = [_MCP_READ_ROLE_PERMISSION, _MCP_WRITE_ROLE_PERMISSION, _DOCUMENT_TEMPLATES_MANAGE_ROLE_PERMISSION]
    , toolset = Just DtMcpToolset
    , transactionState = Transactional
    , run = withArguments arguments $ \(dtUuid, localeUuid) -> object [] <$ deleteLocale dtUuid localeUuid
    }
  where
    arguments = (,) <$> templateUuidArgument <*> requiredArgument "locale_uuid" "The locale to delete"
