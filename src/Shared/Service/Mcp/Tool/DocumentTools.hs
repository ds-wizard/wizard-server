      }

downloadDocumentContent :: WizardRequestContextC s m => U.UUID -> m McpDocumentDownloadDTO
downloadDocumentContent documentUuid = do
  doc <- getDocumentByUuid documentUuid
  unless (doc.state == DoneDocumentState) (throwError . UserError $ _ERROR_SERVICE_MCP__DOCUMENT_NOT_DONE (U.toString documentUuid) (show doc.state))
  expiresAt <- mcpUrlExpiresAt
  (file, content) <- downloadDocumentWithContent mcpTemporaryFileExpiration documentUuid
  let mContent = if isTextContentType (Just file.contentType) then Just (decodeText content) else Nothing
  return $ McpDocumentDownloadDTO documentUuid doc.name file.contentType doc.fileSize file.url expiresAt mContent (fmap length mContent)

