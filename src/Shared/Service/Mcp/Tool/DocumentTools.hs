listDocumentsTool :: forall s m. WizardRequestContextC s m => McpTool m
listDocumentsTool =
  McpTool
    { name = "list_documents"
    , title = "List documents"
    , description =
        "List the documents generated from a project (project_uuid), newest first, with their state, format and submissions; "
          ++ "without project_uuid, or filtered by document_template_uuid, it lists the documents of all projects, which needs projects.edit"
    , inputSchema = argumentsSchema arguments
    , outputSchema = Just $ pageSchema "documents" (jsonSchema (Proxy :: Proxy DocumentDTO))
    , annotations = readOnlyAnnotations
    , continuable = True
    , permissions = [_MCP_READ_ROLE_PERMISSION]
    , toolset = Just ProjectsMcpToolset
    , transactionState = NoTransaction
    , run = withArguments arguments $ \(mProjectUuid, mTemplateUuid, (mQuery, pageable)) ->
        toJSON <$> listDocuments mProjectUuid mTemplateUuid mQuery pageable
    }
  where
    arguments =
      (,,)
        <$> optionalArgument "project_uuid" "Only the documents of this project"
        <*> optionalArgument "document_template_uuid" "Only the documents generated by this document template"
        <*> searchArguments "Search in the names of the documents"
        :: Arguments (Maybe U.UUID, Maybe U.UUID, (Maybe String, Pageable))

listDocuments :: WizardRequestContextC s m => Maybe U.UUID -> Maybe U.UUID -> Maybe String -> Pageable -> m (Page DocumentDTO)
listDocuments (Just projectUuid) Nothing mQuery pageable = getDocumentsForProject projectUuid mQuery pageable documentSort
listDocuments mProjectUuid mTemplateUuid mQuery pageable = getDocumentsPageDto mProjectUuid mTemplateUuid mQuery pageable documentSort

documentSort :: [Sort]
documentSort = [Sort "createdAt" Descending]

createDocumentTool :: WizardRequestContextC s m => McpTool m
createDocumentTool =
  McpTool
    { name = "create_document"
    , title = "Create document"
    , description =
        "Generate a document from a project with its document template, format and language, or with document_template_uuid, format_uuid and language you give; "
          ++ "name defaults to the project name and project_event_uuid to the current replies. "
          ++ "It waits a while for the document worker and returns the document; if it is still queued or in progress, call it again with its uuid as document_uuid. "
