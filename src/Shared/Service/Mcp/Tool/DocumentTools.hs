    }

createDocumentArguments :: Arguments CreateDocumentArguments
createDocumentArguments =
  CreateDocumentArguments
    <$> requiredArgument "project_uuid" "The project"
    <*> optionalArgument "name" "The name of the document"
    <*> optionalArgument "document_template_uuid" "The document template, the one of the project by default"
    <*> optionalArgument "format_uuid" "The format of the document template, the one of the project by default"
    <*> optionalArgument "language" "The language of the document template, the one of the project by default"
    <*> optionalArgument "project_event_uuid" "Generate the document from the replies as they were at this project event (a version)"
    <*> optionalArgument "document_uuid" "The uuid of a queued or in-progress document, to wait for its result"

createDocumentAndWait :: WizardRequestContextC s m => CreateDocumentArguments -> m DocumentDTO
createDocumentAndWait arguments = do
  doc <- withShortConnection (maybe (startDocument arguments) getDocumentByUuid arguments.documentUuid)
  waitSeconds <- asks (.serverConfig'.mcp.documentPreviewWait)
  pollWhile documentProgress waitSeconds (getDocumentByUuid doc.uuid) doc

startDocument :: WizardRequestContextC s m => CreateDocumentArguments -> m DocumentDTO
startDocument arguments = do
  project <- getProjectByUuid arguments.projectUuid
  case documentSettings arguments project of
    (Just documentTemplateUuid, Just formatUuid, mLanguage) ->
      createDocument
        DocumentCreateDTO
          { name = fromMaybe project.name arguments.name
          , projectUuid = project.uuid
          , projectEventUuid = arguments.projectEventUuid
          , documentTemplateUuid = documentTemplateUuid
          , formatUuid = formatUuid
          , language = mLanguage
          }
    _ -> throwError $ UserError _ERROR_SERVICE_DOCUMENT__TEMPLATE_OR_FORMAT_NOT_SET_UP

documentSettings :: CreateDocumentArguments -> Project -> (Maybe U.UUID, Maybe U.UUID, Maybe String)
documentSettings arguments project
  | isJust arguments.documentTemplateUuid = (arguments.documentTemplateUuid, arguments.formatUuid, arguments.language)
  | otherwise = (project.documentTemplateUuid, arguments.formatUuid <|> project.formatUuid, arguments.language <|> project.documentTemplateLanguage)

documentProgress :: DocumentDTO -> Maybe String
documentProgress doc =
  case doc.state of
    QueuedDocumentState -> Just "The document waits for the document worker"
    InProgressDocumentState -> Just "The document worker generates the document"
    _ -> Nothing

